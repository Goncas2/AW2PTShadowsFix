"""Assemble each reviewed build profile and regenerate the C data table."""
import argparse
import json
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def array(data):
    return ','.join(f'0x{byte:02x}' for byte in data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--nasm', default='nasm')
    args = parser.parse_args()
    profiles = json.loads((ROOT / 'data/supported-builds.json').read_text())
    build = ROOT / 'build'
    build.mkdir(exist_ok=True)
    lines = ['/* Generated by tools/generate_data.py; do not edit. */',
             'const AW2Build Aw2Builds[]={']
    seen = set()
    for config in profiles:
        digest = bytes.fromhex(config['sha256'])
        if len(digest) != 32 or digest in seen:
            raise ValueError('Invalid or duplicate build hash.')
        seen.add(digest)
        relocations = config['relocations']
        if len(relocations) != 5 or len(config['patches']) != 8:
            raise ValueError('Expected five external references and eight patch sites.')
        reference = int(config['reference_payload_rva'], 16)
        definitions = {'PATCH_VA': 0x140000000 + reference}
        for name, entry in zip(['STATIC_MANAGER', 'STATIC_REGISTRAR', 'REGISTER_RETURN',
                                'MAIN_RETURN', 'VISIBILITY_RETURN'], relocations):
            definitions[name] = 0x140000000 + int(entry['target'], 16)
        for name, value in zip(['PARENT_BEGIN', 'PARENT_END', 'PARENT_UNWIND'], config['parent']):
            definitions[name] = int(value, 16)
        with tempfile.TemporaryDirectory(dir=build) as directory:
            output = Path(directory) / 'grass.bin'
            subprocess.run([args.nasm, '-f', 'bin', '-o', str(output),
                            *[f'-D{name}={value:#x}' for name, value in definitions.items()],
                            str(ROOT / 'src/grass.asm')], check=True)
            payload = output.read_bytes()
        if len(payload) != 496 or len(payload) != config['payload_size']:
            raise ValueError('Payload layout changed; review offsets and unwind metadata.')
        descriptor = b'\x21\0\0\0' + struct.pack('<III', *[int(v, 16) for v in config['parent']])
        if payload[480:] != descriptor:
            raise ValueError('Unexpected parent unwind descriptor.')
        for entry in relocations:
            at, next_pc, target = (int(entry[k], 16) for k in ('displacement', 'next', 'target'))
            if reference + next_pc + struct.unpack_from('<i', payload, at)[0] != target:
                raise ValueError(f'Unexpected external reference at {at:#x}.')
        lines += ['{', f'.name="{config["name"]}",',
                  f'.file_size={config["file_size"]}u, .timestamp={config["timestamp"]}u,',
                  f'.pe_offset={config["pe_offset"]}u, .image_size={config["image_size"]}u,',
                  '.hash={' + array(digest) + '},',
                  '.payload={' + array(payload) + '},', '.relocations={']
        lines += ['{%s,%s,%s},' % (r['displacement'], r['next'], r['target']) for r in relocations]
        lines += ['},', '.patches={']
        for patch in config['patches']:
            before, after = bytes.fromhex(patch['before']), bytes.fromhex(patch['after'])
            if len(before) != len(after) or len(before) != patch['length'] or len(before) > 24:
                raise ValueError('Invalid patch span.')
            lines.append('{%s,%d,%d,{%s},{%s}},' %
                         (patch['rva'], patch['length'], patch['helper_offset'], array(before), array(after)))
        lines += ['},', f'.scheduling_rva={config["scheduling_rva"]},',
                  '.scheduling_before={' + array(bytes.fromhex(config['scheduling_before'])) + '},',
                  f'.scheduling_control={config["scheduling_control"]},',
                  '.parent={' + ','.join(config['parent']) + '}', '},']
        print(f'Generated {config["name"]}: {len(payload)} payload bytes and eight patch sites.')
    lines.append('};')
    (ROOT / 'src/aw2_data.h').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
