"""Assemble the grass payload and regenerate the checked-in C data header."""
import argparse
import json
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--nasm', default='nasm')
    args = parser.parse_args()
    config = json.loads((ROOT / 'data/supported-build.json').read_text())
    build = ROOT / 'build'
    build.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=build) as directory:
        output = Path(directory) / 'grass.bin'
        subprocess.run([args.nasm, '-f', 'bin', '-o', str(output),
                        str(ROOT / 'src/grass.asm')], check=True)
        payload = output.read_bytes()
    if len(payload) != config['payload_size']:
        raise ValueError('Payload size changed; review the offsets and unwind metadata.')
    if payload[480:] != bytes.fromhex('210000003dc125027bc6250218257c03'):
        raise ValueError('Unexpected parent unwind descriptor.')
    relocations = config['relocations']
    reference = int(config['reference_payload_rva'], 16)
    for entry in relocations:
        at, next_pc, target = (int(entry[k], 16) for k in ('displacement', 'next', 'target'))
        if reference + next_pc + struct.unpack_from('<i', payload, at)[0] != target:
            raise ValueError(f'Unexpected relative reference at {at:#x}.')

    def array(data):
        return ','.join(f'0x{byte:02x}' for byte in data)

    lines = ['/* Generated by tools/generate_data.py; do not edit. */',
             f'#define AW2_SOURCE_SIZE {config["file_size"]}u',
             f'#define AW2_TIMESTAMP {config["timestamp"]}u',
             f'#define AW2_PE_OFFSET {config["pe_offset"]}u',
             f'#define AW2_IMAGE_SIZE {config["image_size"]}u',
             'static const unsigned char aw2_hash[32]={' + array(bytes.fromhex(config['sha256'])) + '};',
             f'static const unsigned char aw2_payload[{len(payload)}]={{' + array(payload) + '};',
             'static const AW2Relocation aw2_relocations[]={']
    lines += ['{%s,%s,%s},' % (r['displacement'], r['next'], r['target']) for r in relocations]
    lines += ['};', 'static const AW2PatchSpec aw2_specs[]={']
    if len(config['patches']) != 8:
        raise ValueError('Expected eight patch sites.')
    for patch in config['patches']:
        before, after = bytes.fromhex(patch['before']), bytes.fromhex(patch['after'])
        if len(before) != len(after) or len(before) != patch['length'] or len(before) > 24:
            raise ValueError('Invalid patch span.')
        lines.append('{%s,%d,%d,{%s},{%s}},' %
                     (patch['rva'], patch['length'], patch['helper_offset'], array(before), array(after)))
    lines.append('};')
    (ROOT / 'src/aw2_data.h').write_text('\n'.join(lines) + '\n')
    print(f'Generated {len(payload)} payload bytes and eight patch sites.')


if __name__ == '__main__':
    main()
